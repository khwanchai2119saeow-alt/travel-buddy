export interface SignHit {
  ja: string; // ข้อความบนป้าย (ญี่ปุ่นหรือจีน — ชื่อฟิลด์เดิม)
  th: string;
}

/** หาคำป้ายที่อยู่ในข้อความ โดยจับคำยาวก่อน (เช่น 立入禁止 ก่อน 禁止) และไม่นับซ้ำส่วนที่จับไปแล้ว */
export function lookupSigns(text: string, country: Country): SignHit[] {
  let rest = text.normalize('NFKC').replace(/\s+/g, '');
  const hits: SignHit[] = [];
  const sorted = [...(country === 'CN' ? SIGNS_ZH : SIGNS_JA)].sort((a, b) => b.ja.length - a.ja.length);
  for (const s of sorted) {
    if (rest.includes(s.ja)) {
      if (!hits.some((h) => h.th === s.th && h.ja === s.ja)) hits.push(s);
      rest = rest.split(s.ja).join('□');
    }
  }
  return hits;
}
